"""Нормализатор адресов. Все примеры взяты из реальной выгрузки."""

import pytest

from planner.ingest.address import normalize


@pytest.mark.parametrize(
    ("raw", "city", "street", "house"),
    [
        ("Город Москва, пр-кт.Волгоградский, д. 128 к 5", "Москва", "Волгоградский проспект", "128к5"),
        ("Город Москва, ул.3-я Институтская, д. 5 к 2", "Москва", "3-я Институтская улица", "5к2"),
        ("Город Москва, ул.Михайлова, д. 14", "Москва", "улица Михайлова", "14"),
        ("Город Москва, ул.Земляной Вал, д. 24/30 стр. 1", "Москва", "улица Земляной Вал", "24/30с1"),
        ("Город Москва, ул.Талалихина, д. 2/1 к 4", "Москва", "улица Талалихина", "2/1к4"),
        ("г.Город Москва, наб.Семеновская, д. 3/1к2", "Москва", "Семеновская набережная", "3/1к2"),
        ("Город Москва, ш.Каширское, д. 94 к 1", "Москва", "Каширское шоссе", "94к1"),
        ("Город Москва, ул.Артюхиной, д. 20А", "Москва", "улица Артюхиной", "20А"),
        ("Город Москва, ул.Красноказарменная, д. 9Б стр. 1", "Москва", "Красноказарменная улица", "9Бс1"),
        ("Москва Булатниковский пр-зд. д. 6к1", "Москва", "Булатниковский проезд", "6к1"),
        ("Москва Бирюлевская ул. д. 44", "Москва", "Бирюлевская улица", "44"),
        ("Москва, проезд Орехово-Зуевский, д. 18/8", "Москва", "Орехово-Зуевский проезд", "18/8"),
        ("Домодедово, ул.Гагарина, д. 55/2", "Домодедово", "улица Гагарина", "55/2"),
        ("Домодедово, проезд.Советский 1-й, д. 1А", "Домодедово", "проезд Советский 1-й", "1А"),
        ("МО, г. Кашира Кржижановского ул. д. 5/1", "Кашира", "улица Кржижановского", "5/1"),
        ("МО, г. Ступино Андропова ул. д. 37", "Ступино", "улица Андропова", "37"),
        ("Кашира, ул.Садовая, д. 2/11", "Кашира", "Садовая улица", "2/11"),
    ],
)
def test_normalize(raw, city, street, house):
    result = normalize(raw)
    assert result.city == city
    assert result.street == street
    assert result.house == house


def test_house_number_not_taken_from_street_type():
    """В «проезд.3-й Павелецкий» подстрока «д.3» не должна стать номером дома."""
    result = normalize("Город Москва, проезд.3-й Павелецкий, д. 9")
    assert result.street == "3-й Павелецкий проезд"
    assert result.house == "9"


def test_korpus_glued_to_house_number():
    """«д. 16к2» — корпус написан вплотную, его нельзя терять."""
    assert normalize("г.Город Москва, ул.Ташкентская, д. 16к2").house == "16к2"


def test_settlement_extracted():
    result = normalize(
        "обл.Московская область, г.Домодедово, пгт.Востряково-1, ул.Жуковского, д. 14/18"
    )
    assert result.city == "Домодедово"
    assert result.settlement == "Востряково-1"
    assert result.house == "14/18"


def test_region_inferred_from_city():
    assert normalize("Город Москва, ул.Окская, д. 32").region == "Москва"
    assert normalize("Кашира, ул.Победы, д. 9").region == "Московская область"


def test_apartment_dropped():
    """Номер квартиры есть в контрольном файле, координатам он не нужен."""
    result = normalize("Город Москва, ул.Окская, д. 32, кв. 42")
    assert result.house == "32"
    assert result.query == "Москва, Окская улица, 32"


def test_house_only_korpus():
    """Самаркандский Квартал 137а: дом задан одним корпусом."""
    assert normalize("Город Москва, б-р.Самаркандский Квартал 137а, д. к5").house == "к5"


def test_query_contains_everything():
    query = normalize("Город Москва, ул.Окская, д. 32").query
    assert query == "Москва, Окская улица, 32"


def test_all_real_addresses_parse():
    """На всей выгрузке у каждого адреса должны определиться улица и дом."""
    from planner.ingest import beeline
    from planner.paths import RAW_DIR

    if not RAW_DIR.is_dir():
        pytest.skip("нет data/raw")
    for scenario in beeline.load_all():
        for order in scenario.orders:
            result = normalize(order.address)
            assert result.street, order.address
            assert result.house, order.address
            assert result.city in ("Москва", "Домодедово", "Кашира", "Ступино"), order.address
