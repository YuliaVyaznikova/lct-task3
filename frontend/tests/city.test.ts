import { describe, expect, it } from 'vitest'

import { addressWithoutCity, cityOf, displayAddress, orderCity, placeLabel } from '../src/derive'

describe('город заявки', () => {
  it('выделяет город из адреса с префиксом Город', () => {
    expect(cityOf('Город Москва, ул.Кустанайская, д. 8 к 1')).toBe('Москва')
  })

  it('выделяет город без префикса Город', () => {
    expect(cityOf('Домодедово, проезд.Советский 1-й, д. 1А')).toBe('Домодедово')
    expect(cityOf('Кашира, ул.Победы, д. 9')).toBe('Кашира')
    expect(cityOf('Ступино, ул.Калинина, д. 34')).toBe('Ступино')
  })

  it('обрабатывает префикс г.Город', () => {
    expect(cityOf('г.Город Москва, наб.Семеновская, д. 3/1к2')).toBe('Москва')
  })

  it('узнаёт Москву в адресе без запятой после города', () => {
    expect(cityOf('Москва Бирюлевская ул. д. 44')).toBe('Москва')
  })
})

describe('адрес без города', () => {
  it('отсекает город до первой запятой', () => {
    expect(addressWithoutCity('Город Москва, ул.Кустанайская, д. 8 к 1')).toBe('ул.Кустанайская, д. 8 к 1')
    expect(addressWithoutCity('Домодедово, проезд.Советский 1-й, д. 1А')).toBe('проезд.Советский 1-й, д. 1А')
  })

  it('убирает город из адреса без запятой', () => {
    expect(addressWithoutCity('Москва Бирюлевская ул. д. 44')).toBe('Бирюлевская ул. д. 44')
  })
})

describe('адрес для показа', () => {
  it('заменяет служебный префикс города на название', () => {
    expect(displayAddress('г.Город Москва, наб.Семеновская, д. 3/1к2')).toBe('Москва, наб.Семеновская, д. 3/1к2')
    expect(displayAddress('Город Москва, ул.Малышева, д. 13')).toBe('Москва, ул.Малышева, д. 13')
    expect(displayAddress('Кашира, ул.Победы, д. 9')).toBe('Кашира, ул.Победы, д. 9')
  })
})

describe('подпись места старта', () => {
  it('показывает районы выездной базы целиком', () => {
    expect(placeLabel('выездная база: Кашира, Ступино')).toBe('Кашира, Ступино')
    expect(placeLabel('выездная база: Домодедово')).toBe('Домодедово')
  })

  it('показывает адрес офиса без города', () => {
    expect(placeLabel('г. Москва, ул Бирюлёвская, д 1с1')).toBe('ул Бирюлёвская, д 1с1')
    expect(placeLabel('г.Москва проезд Симферопольский, д.7')).toBe('проезд Симферопольский, д.7')
  })
})

describe('город заявки для группировки', () => {
  it('берёт район для адресов области', () => {
    expect(orderCity({ address: 'МО, г. Кашира Центральная ул. д. 21', district: 'Кашира' })).toBe('Кашира')
    expect(orderCity({ address: 'обл.Московская область, г.Домодедово, ул.Жуковского', district: 'Домодедово' })).toBe('Домодедово')
  })

  it('сводит все московские адреса в Москву', () => {
    expect(orderCity({ address: 'Город Москва, ул.Малышева, д. 13', district: 'Царицыно' })).toBe('Москва')
    expect(orderCity({ address: 'Москва Бирюлевская ул. д. 44', district: 'Бирюлево Восточное' })).toBe('Москва')
  })
})
